#!/usr/bin/env python3
"""Generate the exact-only 24H32 VCN2 source-pitch patch from signed cache bytes."""
from pathlib import Path
import argparse,hashlib,struct
from gen_vda_va_data import DyldCache,MachOImage,DEFAULT_CACHE_DIR,VA_IMAGE_PATH
ROOT=Path(__file__).resolve().parents[1]
SYMBOL='__ZN11Vcn2Encoder15setEncodeParamsEPvP15VAVendorTexture'
FUNCTION_SHA='c8193ea2d2c7193012a5618b6918d41fffe30ad0c1389256fee983e66ac24347'
FIND=bytes.fromhex('8b8a840000008b87240400000fafc105ff0000002500ffffff31d2f7f1894318d1e889431c')
PAYLOAD=bytes.fromhex('8b82800000008b8a8400000031d2f7f1894318d1e889431c')
REPLACE=PAYLOAD+b'\x90'*(len(FIND)-len(PAYLOAD))

def generate():
    with DyldCache(DEFAULT_CACHE_DIR) as cache:
        assert cache.uuid.hex()=='42ec2890bc40317ebb2745142bff7f26','Unsupported cache UUID'
        image=MachOImage(cache,VA_IMAGE_PATH)
        assert image.uuid.hex()=='662187e49f38375b9bf6ccac3f60979a','Unsupported VA driver UUID'
        address=image.symbol(SYMBOL);length=image.function_end(address)-address
        assert address==0x7ffb0864cac4 and length==138
        code=cache.read(address,length)
        assert hashlib.sha256(code).hexdigest()==FUNCTION_SHA,'Pitch function changed or already patched'
        assert len(FIND)==len(REPLACE)==37 and code[0x31:0x56]==FIND
        page_address=address&~4095;page=cache.read_page(page_address)
        start,_,offset,handle=cache.mapping_for(page_address);file_offset=offset+page_address-start
        handle.seek(0);header=handle.read(80);sigoff,sigsize=struct.unpack_from('<QQ',header,40)
        handle.seek(sigoff);signature=handle.read(sigsize)
        assert struct.unpack_from('>I',signature)[0]==0xfade0cc0
        checked=0
        for index in range(struct.unpack_from('>I',signature,8)[0]):
            _,position=struct.unpack_from('>II',signature,12+8*index)
            if struct.unpack_from('>I',signature,position)[0]!=0xfade0c02:continue
            cd=signature[position:];hash_offset,_,_,count,limit=struct.unpack_from('>5I',cd,16)
            hash_size,hash_type,_,power=struct.unpack_from('4B',cd,36)
            assert 1<<power==4096 and file_offset%4096==0
            slot=file_offset//4096;assert slot<count and file_offset+4096<=limit
            expected=cd[hash_offset+slot*hash_size:hash_offset+(slot+1)*hash_size]
            algorithm={1:'sha1',2:'sha256',3:'sha256',4:'sha384'}[hash_type]
            assert hashlib.new(algorithm,page).digest()[:hash_size]==expected,'Page differs from embedded code signature'
            checked+=1
        assert checked,'No verified CodeDirectory'
        def array(name,data):
            lines=['static const UInt8 '+name+'[] = {']
            lines += ['    '+', '.join(f'0x{x:02X}' for x in data[i:i+16])+',' for i in range(0,len(data),16)]
            return '\n'.join(lines+['};\n'])
        return ('// Generated by tools/gen_vcn_encode_pitch.py; exact signed 24H32 page only.\n'
            '// AMDRadeonVADriver2 UUID 662187E4-9F38-375B-9BF6-CCAC3F60979A.\n'
            '// Vcn2Encoder::setEncodeParams at 0x7FFB0864CAC4, patch +0x31.\n'
            '// Use texture byte stride / element size; preserve native half-width chroma.\n'
            '// Function SHA-256 '+FUNCTION_SHA+'\n'
            '// Page SHA-256 '+hashlib.sha256(page).hexdigest()+'\n'
            '// Driver bytes: Copyright Apple Inc. and Advanced Micro Devices, Inc.\n\n'
            +array('kVAEncodePitchPage_Sequoia',page)+array('kVAEncodePitchFind',FIND)
            +array('kVAEncodePitchReplace',REPLACE))

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    args=parser.parse_args();output=ROOT/'NootedRed/UserPatchesVAEncode.inc';text=generate()
    if args.check:assert output.read_text()==text,'Generated pitch data differs'
    else:output.write_text(text)
    print('Verified signed Sequoia VCN2 function/page; '+('data matches' if args.check else str(output)))
