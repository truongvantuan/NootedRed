// Identities of the reference shared caches used by the fixed-offset Metal hooks.
#pragma once
#include <IOKit/IOTypes.h>
#include <libkern/libkern.h>

namespace UserSharedCacheData {
    inline constexpr UInt8 magic[16] = {'d','y','l','d','_','v','1',' ','x','8','6','_','6','4','h',0};
    inline constexpr UInt8 ventura[16] = {
        0x8E,0xEE,0x66,0x86,0x4D,0x40,0x33,0xA3,0xB0,0x7B,0xB3,0x34,0xFD,0x3E,0x3E,0xCC};
    inline constexpr UInt8 sonoma[16] = {
        0x4C,0x14,0x41,0xFD,0x8A,0x54,0x3D,0xC2,0x86,0x3D,0x49,0x11,0x0B,0x94,0x6A,0x25};
    inline constexpr UInt8 sequoia[16] = {
        0x42,0xEC,0x28,0x90,0xBC,0x40,0x31,0x7E,0xBB,0x27,0x45,0x14,0x2B,0xFF,0x7F,0x26};
    // 15.8.2 (24H232) retains the submit-method address/prologue. The existing
    // guard payload still needs hardware validation on this build. LegacyBlend
    // independently checks its complete page variant.
    inline constexpr UInt8 sequoia24H232[16] = {
        0x90,0xDB,0x0D,0xEB,0x23,0x44,0x36,0x01,0xB0,0x11,0xB8,0x73,0x12,0xD7,0x4C,0xFB};
    inline constexpr UInt8 tahoe[16] = {
        0x31,0x37,0x47,0x56,0x89,0xB4,0x34,0xE8,0xA3,0x4F,0x56,0xC5,0xD5,0x72,0x16,0xA1};

    inline bool matches(UInt32 major, const UInt8* header)
    {
        const auto* uuid = major == 22 ? ventura : major == 23 ? sonoma : major == 24 ? sequoia : major == 25 ? tahoe : nullptr;
        return uuid != nullptr && memcmp(header, magic, sizeof(magic)) == 0
               && (memcmp(header + 88, uuid, 16) == 0
                   || (major == 24 && memcmp(header + 88, sequoia24H232, 16) == 0));
    }
}
